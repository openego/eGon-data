def get_lpg_hh_demand_profiles_raw():
    """Gets and returns household electricity demand profiles from the
    Load Profile Generator (LPG), stored in the egon-data-bundle.

    Profiles are generated by LPG for multi-family houses (mfh) and cover
    household archetypes of two series: CHR (CHR01-CHR61) and CHS (CHS01,
    CHS04, CHS12). All types are mapped to the same 10 Eurostat/IEE household
    type buckets used by the IEE profiles (SR, SO, SK, PR, PO, P1, P2, P3,
    OR, OO) so all downstream processing remains unchanged.

    Notes
    -----
    The LPG profiles are originally at 15-minute resolution for year 2011
    (one CSV per household-type × seed combination). The Parquet bundle file
    is prepared externally by:
      1. Reading each CSV (``Electricity_HH1`` column, 35,040 rows)
      2. Resampling 15-min → 1-hour (sum 4 intervals per hour)
      3. Converting kWh → Wh (multiply by 1000)
      4. Storing as a single DataFrame ``(8760, N_profiles)`` via
         ``df.to_parquet()`` with a ``DatetimeIndex`` for 2011

    Column format in Parquet: ``{HH_TYPE}a{id:05d}``,
    e.g. ``CHR01a00001``, ``CHS04a00003``

    The profiles cover year 2011, so no date-alignment step is needed
    (unlike IEE profiles which are 2016-based and require dropping day 1).

    Returns
    -------
    pd.DataFrame
        Table with profiles in columns and time as index, with IEE-compatible
        column names (e.g. ``POa00001``, ``SRa00003``).
    """

    def ve(s):
        raise ValueError(s)

    dataset = egon.data.config.settings()["egon-data"]["--dataset-boundary"]

    file_section = (
        "path"
        if dataset == "Everything"
        else (
            "path_testmode"
            if dataset == "Schleswig-Holstein"
            else ve(f"'{dataset}' is not a valid dataset boundary.")
        )
    )

    from egon.data.datasets.electricity_demand_timeseries.hh_profiles import (
        HouseholdDemands,
    )

    file_path = HouseholdDemands.sources.files[
        "lpg_household_electricity_demand_profiles"
    ][file_section]

    download_directory = os.path.join(
        "data_bundle_egon_data", "household_electricity_demand_profiles"
    )

    hh_profiles_file = Path(".") / Path(download_directory) / Path(file_path)

    df_lpg_profiles = pd.read_parquet(hh_profiles_file)

    # Rename columns from LPG-type format to IEE bucket format.
    # Multiple household types map to the same bucket; IDs are renumbered
    # sequentially within each bucket so there are no collisions.
    bucket_counters = {}
    new_columns = []
    for col in df_lpg_profiles.columns:
        hh_type = col[:5]  # e.g. "CHR01" or "CHS04"
        if hh_type not in CHR_TO_HH_TYPE:
            raise ValueError(
                f"Unknown household type '{hh_type}' in LPG profiles file. "
                "Update CHR_TO_HH_TYPE mapping."
            )
        bucket = CHR_TO_HH_TYPE[hh_type]
        idx = bucket_counters.get(bucket, -1) + 1
        bucket_counters[bucket] = idx
        new_columns.append(f"{bucket}a{idx:05d}")
    df_lpg_profiles.columns = new_columns

    return df_lpg_profiles